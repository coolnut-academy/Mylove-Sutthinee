import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { AppsScriptDataProvider } from '../js/data/apps-script-provider.js';
import { AppState } from '../js/app-state.js';

const reads = [];
const categories = 'students attendance teeth milk growth health sdq pp media plc research plan awards sar other'.split(' ');
const tables = Object.fromEntries(['STUDENTS', 'ATTENDANCE', 'DAILY_ROUTINES', 'HEALTH', 'SDQ'].map(name => [name, [{ year: 2567, id: name }]]));
tables.CLASSROOM_DOCUMENTS = categories.map(category => ({ year: 2567, category, fields: '[{"label":"name","value":"test"}]' }));
tables.CLASSROOM_DOCUMENTS.push({ year: 2567, archived: true }, { year: 2568 });
const context = vm.createContext({ Sheets: { getTable(name) { reads.push(name); return structuredClone(tables[name]); } } });
vm.runInContext(fs.readFileSync('apps-script/Classroom.gs', 'utf8') + '\nglobalThis.Classroom = Classroom;', context);
const full = context.Classroom.getData('2567');
assert.equal(reads.length, 6);
reads.length = 0;
const cards = context.Classroom.getData('2567', true);
assert.deepEqual(JSON.parse(JSON.stringify(cards.documents)), JSON.parse(JSON.stringify(full.documents)));
assert.equal(cards.documents.length, 15);
assert.deepEqual(reads, ['CLASSROOM_DOCUMENTS']);
reads.length = 0;
assert.equal(context.Classroom.getStudents('2567').length, 1);
assert.deepEqual(reads, ['STUDENTS']);
// The next request must observe direct spreadsheet changes, with no stale cache.
tables.CLASSROOM_DOCUMENTS[0].title = 'edited';
assert.equal(context.Classroom.getData('2567', true).documents[0].title, 'edited');
tables.CLASSROOM_DOCUMENTS.splice(0, 1);
assert.equal(context.Classroom.getData('2567', true).documents.length, 14);

const provider = new AppsScriptDataProvider('https://example.invalid');
const calls = [];
provider._sendRequest = (action, params) => new Promise((resolve, reject) => calls.push({ action, params, resolve, reject }));
const settings = provider.getSettings(), years = provider.getYears();
assert.equal(calls.length, 1, 'settings and years share one bootstrap request');
calls[0].resolve({ settings: { title: 'test' }, years: [2567] });
assert.deepEqual(await settings, { title: 'test' });
assert.deepEqual(await years, [2567]);
let first = provider.getClassroomData('2567', { documentsOnly: true });
let duplicate = provider.getClassroomData('2567', { documentsOnly: true });
assert.equal(calls.length, 2);
assert.equal(calls[1].params.documentsOnly, true);
const write = provider.saveClassroomDocument({ year: 2567 });
const duringWrite = provider.getClassroomData('2567', { documentsOnly: true });
assert.equal(calls.length, 4, 'a mutation separates subsequent reads from older pending requests');
calls[2].resolve({ id: 'saved' }); await write;
const afterWrite = provider.getClassroomData('2567', { documentsOnly: true });
assert.equal(calls.length, 5, 'post-save read cannot join a read started during the save');
calls[1].resolve({ documents: [] }); calls[3].resolve({ documents: [] }); calls[4].resolve({ documents: [{ id: 'saved' }] });
await Promise.all([first, duplicate, duringWrite]);
assert.equal((await afterWrite).documents[0].id, 'saved');
const fail = provider.getYears(); calls.at(-1).reject(new Error('network'));
await assert.rejects(fail, /network/);
const retry = provider.getYears(); calls.at(-1).resolve({ years: [2568] });
assert.deepEqual(await retry, [2568]);
const pa = provider.getPaData(2567);
assert.equal(calls.at(-1).action, 'getPaData');
calls.at(-1).resolve({ sections: [1], items: [2] });
assert.deepEqual(await pa, { sections: [1], items: [2] });
const oldSession = AppState.session;
const publicRead = provider.getStudents(2567);
AppState.session = { token: 'test-only' };
const privateRead = provider.getStudents(2567);
assert.equal(calls.at(-1) === calls.at(-2), false);
calls.at(-1).resolve([]); calls.at(-2).resolve([]);
await Promise.all([publicRead, privateRead]);
AppState.session = oldSession;
assert.equal(provider._pendingReads.size, 0);
console.log('Read performance passed: 6→1 sheet reads, all 15 categories preserved, fresh edits/deletes, bootstrap deduplication, mutation/session boundaries, failed-read retry, combined PA.');
